// Records come unchanged from original pi-durable 1.5.0 MemoryStorage
// (scripts/capture-durable-entry-records.mjs). A drop-in Conversation/Entry
// must import and re-export them byte-equivalently.
func TestPiDurableV150ConversationEntryWire(t *testing.T) {
	data, err := os.ReadFile("testdata/pi-durable-v150/entry-records.json")
	if err != nil {
		t.Fatal(err)
	}
	var fixture struct {
		Target        string            `json:"target"`
		Conversations []json.RawMessage `json:"conversations"`
		Entries       []json.RawMessage `json:"entries"`
	}
	if err = json.Unmarshal(data, &fixture); err != nil || fixture.Target != "f9a26365568127461c47a07a37dcb42c140a3ac5" {
		t.Fatal("fixture provenance", err)
	}
	check := func(t *testing.T, raw json.RawMessage, target any) {
		if err := json.Unmarshal(raw, target); err != nil {
			t.Fatalf("valid original record rejected: %v", err)
		}
		got, err := json.Marshal(reflect.ValueOf(target).Elem().Interface())
		if err != nil {
			t.Fatal(err)
		}
		if !reflect.DeepEqual(dropinJSON(t, got), dropinJSON(t, raw)) {
			t.Fatalf("got %s\noriginal %s", got, raw)
		}
	}
	for _, raw := range fixture.Conversations {
		t.Run("conversation", func(t *testing.T) { check(t, raw, &Conversation{}) })
	}
	for _, raw := range fixture.Entries {
		t.Run("entry", func(t *testing.T) { check(t, raw, &Entry{}) })
	}
}

// The string arm and explicit zero timestamp are captured from unchanged
// original MemoryStorage, not generated by a native acceptance normaliser.
func TestOriginalStringMessageContentSurvivesSQLiteAndProviderProjection(t *testing.T) {
	data, err := os.ReadFile("testdata/pi-durable-v150/entry-records.json")
	if err != nil {
		t.Fatal(err)
	}
	var fixture struct{ Entries []json.RawMessage }
	if err = json.Unmarshal(data, &fixture); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(t.TempDir(), "messages.sqlite")
	store, err := OpenSQLite(path, SQLiteOptions{})
	if err != nil {
		t.Fatal(err)
	}
	defer store.Close(bg)
	writes := []StorageWrite{{Type: "conversation", Value: Conversation{ID: 1}}}
	original := map[ID]json.RawMessage{}
	for _, wire := range fixture.Entries {
		var entry Entry
		if err = json.Unmarshal(wire, &entry); err != nil {
			t.Fatal(err)
		}
		if entry.ID != 2 && entry.ID < 10 {
			continue
		}
		writes = append(writes, StorageWrite{Type: "entry", Value: entry})
		original[entry.ID] = wire
	}
	if result, err := store.Commit(bg, [][]StorageWrite{writes}, nil); err != nil || result.Stored != 1 {
		t.Fatal(result, err)
	}
	if err = store.Close(bg); err != nil {
		t.Fatal(err)
	}
	store, err = OpenSQLite(path, SQLiteOptions{})
	if err != nil {
		t.Fatal(err)
	}
	defer store.Close(bg)
	for id, wire := range original {
		record, found, err := store.Entry(bg, id)
		if err != nil || !found {
			t.Fatal(record, found, err)
		}
		encoded, err := json.Marshal(record.Entry)
		if err != nil || !reflect.DeepEqual(dropinJSON(t, encoded), dropinJSON(t, wire)) {
			t.Fatalf("changed original record after SQLite reopen: %s / %s / %v", encoded, wire, err)
		}
		for _, receipt := range record.Entry.Model {
			if receipt.ContentText == nil {
				continue
			}
			message := receiptMessage(receipt)
			if len(message.Content) != 1 || message.Content[0].Type != "text" || message.Content[0].Text != *receipt.ContentText {
				t.Fatal("provider projection changed string content", message)
			}
		}
	}
}

func TestMessageContentUnionOwnershipBudgetsAndAuthority(t *testing.T) {
	text := ""
	receipt := MessageReceipt{Role: goai.RoleUser, ContentText: &text, Timestamp: 0}
	encoded, err := encodeBounded(JSON{"message": receipt}, DefaultLimits(), DefaultLimits().MaxRecordBytes)
	if err != nil {
		t.Fatal(err)
	}
	var result struct {
		Message MessageReceipt `json:"message"`
	}
	if err = decodeStrict(encoded, DefaultLimits(), DefaultLimits().MaxRecordBytes, &result); err != nil {
		t.Fatal(err)
	}
	text = "changed"
	if result.Message.ContentText == nil || *result.Message.ContentText != "" || result.Message.Content != nil {
		t.Fatal("decoded string content aliases caller or lost its arm", result)
	}
	for _, invalid := range []MessageReceipt{{Role: goai.RoleUser, ContentText: &text, Content: []goai.ContentBlock{}}, {Role: goai.RoleAssistant, ContentText: &text}, {Role: goai.RoleToolResult, ContentText: &text}} {
		if _, err = json.Marshal(invalid); err == nil {
			t.Fatal("invalid content union admitted", invalid)
		}
	}
	limit := DefaultLimits()
	limit.MaxStringBytes = 4
	large := "too long"
	if _, err = encodeBounded(JSON{"message": MessageReceipt{Role: goai.RoleUser, ContentText: &large}}, limit, limit.MaxRecordBytes); err == nil {
		t.Fatal("string content bypassed JSON byte limit")
	}
}
