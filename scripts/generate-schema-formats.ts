#!/usr/bin/env bun
// Generate only the reviewed TypeBox regex formats, not all format support.
// Usage: make generate-schema-formats UPSTREAM_REPO=/path/to/upstream-git-repository
// For direct invocation, first source scripts/project-env.sh.
import { join, resolve } from "node:path";

const pin = "c9f4c7b9fcd0f3e6b5bbc35c7c9b6cda35580eb8";
const repository = process.argv[2];
if (!repository || process.argv.length !== 3) throw new Error("usage: generate-schema-formats.ts <upstream-git-repository>");
const definitions: string[] = [];
for (const name of ["email", "uri", "uuid", "ipv4"]) {
  const path = `packages/schema/src/formats/typebox/${name}.ts`;
  const source = Bun.spawnSync(["git", "-C", resolve(repository), "show", `${pin}:${path}`]);
  if (source.exitCode !== 0) throw new Error(source.stderr.toString());
  const match = source.stdout.toString().match(/^const \w+\s*=\s*\/([^\n]+)\/([a-z]*);$/m);
  if (!match || (match[2] !== "i" && match[2] !== "")) throw new Error(`unsupported format definition: ${path}`);
  // ASCII-only folding is done on the input. Go's Unicode (?i) would admit
  // Kelvin sign/long s where the upstream non-Unicode JS /i rejects them.
  const pattern = match[1].replaceAll("\\/", "/").replace("IPv6:", "ipv6:");
  if (/[A-Z]/.test(pattern)) throw new Error(`unreviewed case-sensitive token: ${path}`);
  definitions.push(`\t${JSON.stringify(name)}: regexp.MustCompile(${JSON.stringify(pattern)}),`);
}
const generated = `// Code generated by scripts/generate-schema-formats.ts; DO NOT EDIT.
// Source: ${pin}, packages/schema/src/formats/typebox/{email,uri,uuid,ipv4}.ts.
// TypeBox, Copyright (c) 2017-2026 Haydn Paterson, MIT; see THIRD_PARTY_NOTICES.md.

package goai

import "regexp"

var schemaFormatPatterns = map[string]*regexp.Regexp{
${definitions.join("\n")}
}
`;
const goroot = Bun.spawnSync([process.env.GO ?? "go", "env", "GOROOT"]);
if (goroot.exitCode !== 0) throw new Error(goroot.stderr.toString());
const formatted = Bun.spawnSync([join(goroot.stdout.toString().trim(), "bin", "gofmt")], { stdin: Buffer.from(generated) });
if (formatted.exitCode !== 0) throw new Error(formatted.stderr.toString());
await Bun.write(resolve(import.meta.dir, "../schema_formats_generated.go"), formatted.stdout);
